#!/usr/bin/env python3
"""Generate the Japanese home page (ja/index.html) from the English one.

The site's language model is URL-based: English at /path/, Japanese at /ja/path/.
The home page's English markup (index.html) is the source of truth; every
translatable element carries ``data-i18n="<key>"`` (inner content) or
``data-i18n-attr="attr:key,..."`` (attribute values), and the Japanese text for
each key lives under ``page.home`` in ``i18n/strings.ja.json``.

This script applies those strings at build time and writes ``ja/index.html`` —
a normal Jekyll page using the same ``home`` layout, nav and footer as ``/``.
It also points internal links at their /ja/ counterparts when one exists, so a
reader who is in Japanese stays in Japanese.

    python3 scripts/build_ja_home.py           # regenerate ja/index.html
    python3 scripts/build_ja_home.py --check   # CI: fail if stale or a key is missing

Rules (same contract the old runtime applier used):
  * keys ending in ``.html`` are inserted as markup; all others as escaped text
  * a key with no JA string is an error (no silent English on the JA page)
"""
from __future__ import annotations

import argparse
import difflib
import html
import json
import re
import sys
from html.parser import HTMLParser
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INDEX = ROOT / "index.html"
STRINGS = ROOT / "i18n" / "strings.ja.json"
JA_DIR = ROOT / "ja"
OUT = JA_DIR / "index.html"
NAMESPACE = "page.home"
FRONT_MATTER_KEYS = ("title", "meta.description")  # used in front matter, not the body

VOID = {"area", "base", "br", "col", "embed", "hr", "img", "input", "link",
        "meta", "source", "track", "wbr"}

BANNER = (
    "<!-- GENERATED by scripts/build_ja_home.py from index.html + i18n/strings.ja.json.\n"
    "     Do not edit: change index.html (EN) or the JA string, then re-run the script. -->\n"
)


# ---------------------------------------------------------------- front matter

def split_front_matter(text: str) -> tuple[str, str]:
    m = re.match(r"---\n(.*?)\n---\n", text, re.S)
    if not m:
        raise SystemExit("ERROR: index.html has no front matter")
    return m.group(1), text[m.end():]


def front_matter_permalink(path: Path) -> str | None:
    text = path.read_text(encoding="utf-8")
    if not text.startswith("---"):
        return None
    fm = text.split("---", 2)[1]
    m = re.search(r"^permalink:\s*['\"]?([^'\"\s]+)", fm, re.M)
    return m.group(1) if m else None


def ja_permalinks(ja_dir: Path = JA_DIR) -> set[str]:
    """Every URL that has a Japanese page (from front-matter permalinks)."""
    urls = set()
    for path in ja_dir.rglob("*"):
        if path.suffix in (".md", ".html") and path.is_file():
            url = front_matter_permalink(path)
            if url:
                urls.add(url)
    return urls


# ---------------------------------------------------------------- translation

def localize_href(href: str, ja_urls: set[str]) -> str:
    """/x/#y -> /ja/x/#y when /ja/x/ exists; / -> /ja/. Other hrefs unchanged."""
    if not href.startswith("/") or href.startswith("//") or href.startswith("/ja/"):
        return href
    path, sep, frag = href.partition("#")
    if path == "/":
        return "/ja/" + sep + frag
    candidate = "/ja" + path
    if candidate in ja_urls:
        return candidate + sep + frag
    return href


def set_attr(raw_tag: str, attr: str, value: str) -> str:
    pattern = re.compile(r'(\s' + re.escape(attr) + r'=")[^"]*(")')
    if not pattern.search(raw_tag):
        raise ValueError(f"attribute {attr!r} not found in {raw_tag}")
    return pattern.sub(lambda m: m.group(1) + value + m.group(2), raw_tag, count=1)


class Translator(HTMLParser):
    """Re-emits the input markup verbatim except for data-i18n content,
    data-i18n-attr attributes and internal hrefs."""

    def __init__(self, strings: dict | None, ja_urls: set[str] | None):
        super().__init__(convert_charrefs=False)
        self.strings = strings
        self.ja_urls = ja_urls
        self.out: list[str] = []
        self.used: set[str] = set()
        self.missing: list[str] = []
        self._skip_tag: str | None = None
        self._skip_depth = 0

    # -- helpers
    def _lookup(self, key: str) -> str | None:
        self.used.add(key)
        value = self.strings.get(key)
        if value is None:
            self.missing.append(key)
        return value

    def _rewrite_tag(self, tag: str, attrs: list[tuple[str, str | None]], raw: str) -> str:
        if self.strings is None:
            return raw
        a = dict(attrs)
        spec = a.get("data-i18n-attr")
        if spec:
            for pair in spec.split(","):
                name, _, key = (p.strip() for p in pair.partition(":"))
                value = self._lookup(key)
                if value is not None:
                    raw = set_attr(raw, name, html.escape(value, quote=True))
        if tag == "a" and a.get("href") and self.ja_urls is not None:
            new = localize_href(a["href"], self.ja_urls)
            if new != a["href"]:
                raw = set_attr(raw, "href", new)
        return raw

    # -- parser callbacks
    def handle_starttag(self, tag, attrs):
        if self._skip_tag:
            if tag == self._skip_tag:
                self._skip_depth += 1
            return
        raw = self._rewrite_tag(tag, attrs, self.get_starttag_text())
        self.out.append(raw)
        key = dict(attrs).get("data-i18n")
        if key and self.strings is not None and tag not in VOID:
            value = self._lookup(key)
            if value is not None:
                self.out.append(value if key.endswith(".html") else html.escape(value, quote=False))
                self._skip_tag, self._skip_depth = tag, 1

    def handle_startendtag(self, tag, attrs):
        if self._skip_tag:
            return
        self.out.append(self._rewrite_tag(tag, attrs, self.get_starttag_text()))

    def handle_endtag(self, tag):
        if self._skip_tag:
            if tag == self._skip_tag:
                self._skip_depth -= 1
                if self._skip_depth == 0:
                    self._skip_tag = None
                    self.out.append(f"</{tag}>")
            return
        self.out.append(f"</{tag}>")

    def handle_data(self, data):
        if not self._skip_tag:
            self.out.append(data)

    def handle_entityref(self, name):
        if not self._skip_tag:
            self.out.append(f"&{name};")

    def handle_charref(self, name):
        if not self._skip_tag:
            self.out.append(f"&#{name};")

    def handle_comment(self, data):
        if not self._skip_tag:
            self.out.append(f"<!--{data}-->")

    def handle_decl(self, decl):
        self.out.append(f"<!{decl}>")


def translate(body: str, strings: dict | None, ja_urls: set[str] | None) -> Translator:
    t = Translator(strings, ja_urls)
    t.feed(body)
    t.close()
    return t


# ---------------------------------------------------------------- build

def load_strings(path: Path = STRINGS) -> dict:
    data = json.loads(path.read_text(encoding="utf-8"))
    if NAMESPACE not in data:
        raise SystemExit(f"ERROR: {path.name} has no {NAMESPACE!r} namespace")
    return data[NAMESPACE]


def yaml_str(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)  # a JSON string is a valid YAML scalar


def build(index_text: str, strings: dict, ja_urls: set[str]) -> tuple[str, list[str], list[str]]:
    """Return (ja page text, missing keys, unused keys)."""
    _, body = split_front_matter(index_text)
    t = translate(body, strings, ja_urls)
    missing = list(dict.fromkeys(t.missing))
    for key in FRONT_MATTER_KEYS:
        if key not in strings:
            missing.append(key)
    unused = sorted(set(strings) - t.used - set(FRONT_MATTER_KEYS))
    fm = (
        "---\n"
        "layout: home\n"
        "lang: ja\n"
        f"title: {yaml_str(strings.get('title', ''))}\n"
        f"description: {yaml_str(strings.get('meta.description', ''))}\n"
        "permalink: /ja/\n"
        "---\n"
    )
    return fm + BANNER + "".join(t.out), missing, unused


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if ja/index.html is stale")
    args = ap.parse_args(argv)

    urls = ja_permalinks()
    urls.discard("/ja/")
    text, missing, unused = build(INDEX.read_text(encoding="utf-8"), load_strings(), urls)

    if unused:
        print(f"warning: {len(unused)} JA string(s) not used by index.html: {', '.join(unused)}",
              file=sys.stderr)
    if missing:
        print("ERROR: index.html uses keys with no JA string in i18n/strings.ja.json "
              f"({NAMESPACE}): {', '.join(missing)}", file=sys.stderr)
        return 1

    current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
    if args.check:
        if current != text:
            sys.stdout.writelines(difflib.unified_diff(
                current.splitlines(True), text.splitlines(True),
                "ja/index.html (committed)", "ja/index.html (generated)"))
            print("\nERROR: ja/index.html is stale. Run: python3 scripts/build_ja_home.py",
                  file=sys.stderr)
            return 1
        print("ja/index.html is in sync")
        return 0
    if current == text:
        print("ja/index.html already in sync; nothing to do")
    else:
        OUT.write_text(text, encoding="utf-8")
        print(f"updated {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
